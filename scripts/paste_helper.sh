#!/usr/bin/env bash
# paste_helper.sh - quick mobile paste instructions for Samsung A73
# Add this file to the repo to give step-by-step copy/paste instructions on mobile.

cat <<'EOF'
Tuji Store - Paste Helper

Quick steps to paste code from this chat into a mobile editor (Samsung A73):
1) Open this repository in Chrome (top) and your editor app (e.g., QuickEdit, Samsung Notes) in split-screen (bottom).
   - Recent apps -> app icon -> Open in split screen view -> choose editor for bottom pane.
2) In the chat (top pane) tap the code block, long-press to Copy.
3) Tap the editor (bottom pane) -> long-press in the edit area -> Paste.
4) Save the file with correct filename and extension (e.g., scripts/yourfile.js).
5) If you need the file locally: open this file in GitHub, tap 'Raw', long-press and choose 'Download' or 'Open in' to send to an editor app.

If split-screen is not available:
- Copy small chunks to Samsung Notes or Google Keep and paste into editor.
- Or tap Share -> choose Email/Drive/Keep to move the text off the chat app before editing.
EOF
